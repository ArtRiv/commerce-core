import { randomBytes } from 'node:crypto';

import * as argon2 from 'argon2';

import type { PrismaClient } from '../generated/prisma/client';
import { normalizeEmail } from './normalize-email';

export interface CreateAdminInput {
  email: string;
  name?: string;
  password?: string;
}

export interface CreateAdminOutput {
  user: {
    id: string;
    email: string;
    name: string | null;
    role: string;
  };
  password: string;
  isNewUser: boolean;
  passwordAutoGenerated: boolean;
}

export interface ParsedAdminCliArgs {
  email?: string;
  name?: string;
  password?: string;
  help?: boolean;
}

/**
 * Valida o formato de e-mail básico para garantir integridade.
 */
export function isValidEmail(email: string): boolean {
  const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  return emailRegex.test(email.trim());
}

/**
 * Gera uma senha aleatória de alta entropia contendo letras maiúsculas,
 * minúsculas, números e caracteres especiais seguros.
 */
export function generateSecurePassword(length = 16): string {
  const charset =
    'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnpqrstuvwxyz23456789!@#$%&*';
  const bytes = randomBytes(length);
  let password = '';
  for (let i = 0; i < length; i++) {
    const byte = bytes[i] ?? 0;
    password += charset[byte % charset.length];
  }
  return password;
}

/**
 * Interpreta argumentos passados via CLI (suporta flags curtas e longas com = ou espaço).
 * Ex: --email=admin@loja.com, --email admin@loja.com, -e admin@loja.com
 */
export function parseAdminCliArgs(args: string[]): ParsedAdminCliArgs {
  const parsed: ParsedAdminCliArgs = {};

  for (let i = 0; i < args.length; i++) {
    const arg = args[i] ?? '';

    if (arg === '--help' || arg === '-h') {
      parsed.help = true;
      return parsed;
    }

    if (arg.startsWith('--email=')) {
      parsed.email = arg.split('=', 2)[1];
    } else if (arg === '--email' || arg === '-e') {
      parsed.email = args[++i];
    } else if (arg.startsWith('--name=')) {
      parsed.name = arg.split('=', 2)[1];
    } else if (arg === '--name' || arg === '-n') {
      parsed.name = args[++i];
    } else if (arg.startsWith('--password=')) {
      parsed.password = arg.split('=', 2)[1];
    } else if (arg === '--password' || arg === '-p') {
      parsed.password = args[++i];
    }
  }

  return parsed;
}

